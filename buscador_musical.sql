-- =====================================================================
-- Buscador semántico de música con historial de usuario (RAG)
-- Base de datos PostgreSQL + pgvector
-- Requiere: PostgreSQL 13+ y pgvector 0.5+ (HNSW)
-- =====================================================================

-- Para crear la base de datos (ejecutar conectado a otra BD, p. ej. postgres):
--   CREATE DATABASE buscador_musical ENCODING 'UTF8';
--   \c buscador_musical

BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;

-- =====================================================================
-- 1. DOMINIO: CATÁLOGO MUSICAL
-- =====================================================================

CREATE TABLE pais (
    id_pais   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre    VARCHAR(100) NOT NULL,
    CONSTRAINT pk_pais        PRIMARY KEY (id_pais),
    CONSTRAINT uq_pais_nombre UNIQUE (nombre)
);

CREATE TABLE sello_discografico (
    id_sello   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(150) NOT NULL,
    sitio_web  VARCHAR(255),
    CONSTRAINT pk_sello        PRIMARY KEY (id_sello),
    CONSTRAINT uq_sello_nombre UNIQUE (nombre)
);

CREATE TABLE genero (
    id_genero    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(80) NOT NULL,
    descripcion  TEXT,
    CONSTRAINT pk_genero        PRIMARY KEY (id_genero),
    CONSTRAINT uq_genero_nombre UNIQUE (nombre)
);

CREATE TABLE tema (
    id_tema      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(100) NOT NULL,
    descripcion  TEXT,
    CONSTRAINT pk_tema        PRIMARY KEY (id_tema),
    CONSTRAINT uq_tema_nombre UNIQUE (nombre)
);

CREATE TABLE idioma (
    id_idioma   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(80)  NOT NULL,
    codigo_iso  VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_idioma        PRIMARY KEY (id_idioma),
    CONSTRAINT uq_idioma_nombre UNIQUE (nombre),
    CONSTRAINT uq_idioma_iso    UNIQUE (codigo_iso)
);

CREATE TABLE artista (
    id_artista       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre_artistico VARCHAR(150) NOT NULL,
    tipo_artista     VARCHAR(20)  NOT NULL,
    id_pais          INTEGER,
    fecha_inicio     DATE,
    fecha_fin        DATE,
    CONSTRAINT pk_artista PRIMARY KEY (id_artista),
    CONSTRAINT fk_artista_pais FOREIGN KEY (id_pais)
        REFERENCES pais (id_pais) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_artista_tipo CHECK (tipo_artista IN ('solista', 'banda', 'otro')),
    CONSTRAINT ck_artista_fechas CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE album (
    id_album          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    titulo            VARCHAR(200) NOT NULL,
    fecha_lanzamiento DATE,
    tipo_lanzamiento  VARCHAR(30),
    id_sello          INTEGER,
    CONSTRAINT pk_album PRIMARY KEY (id_album),
    CONSTRAINT fk_album_sello FOREIGN KEY (id_sello)
        REFERENCES sello_discografico (id_sello) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE cancion (
    id_cancion        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    titulo            VARCHAR(200) NOT NULL,
    duracion_segundos INTEGER,
    es_explicita      BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_lanzamiento DATE,
    CONSTRAINT pk_cancion PRIMARY KEY (id_cancion),
    CONSTRAINT ck_cancion_duracion CHECK (duracion_segundos > 0)
);

CREATE TABLE imagen (
    id_imagen         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ruta_archivo      VARCHAR(500) NOT NULL,
    descripcion       TEXT,
    texto_alternativo VARCHAR(300),
    fuente            VARCHAR(255),
    fecha_registro    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_imagen PRIMARY KEY (id_imagen)
);

CREATE TABLE archivo_audio (
    id_audio            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cancion          BIGINT NOT NULL,
    ubicacion_archivo   TEXT NOT NULL,
    formato             VARCHAR(10) NOT NULL,
    duracion_segundos   NUMERIC(10,3) NOT NULL,
    frecuencia_muestreo INTEGER,
    CONSTRAINT pk_archivo_audio PRIMARY KEY (id_audio),
    CONSTRAINT fk_audio_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_audio_duracion   CHECK (duracion_segundos > 0),
    CONSTRAINT ck_audio_frecuencia CHECK (frecuencia_muestreo IS NULL OR frecuencia_muestreo > 0)
);

-- ---------------------------------------------------------------------
-- Tablas puente del catálogo (relaciones N:M)
-- ---------------------------------------------------------------------

-- Si un artista tiene un único rol por canción, basta con (id_cancion, id_artista).
CREATE TABLE cancion_artista (
    id_cancion BIGINT      NOT NULL,
    id_artista INTEGER     NOT NULL,
    rol        VARCHAR(40) NOT NULL,
    CONSTRAINT pk_cancion_artista PRIMARY KEY (id_cancion, id_artista, rol),
    CONSTRAINT fk_ca_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ca_artista FOREIGN KEY (id_artista)
        REFERENCES artista (id_artista) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE album_cancion (
    id_album     INTEGER NOT NULL,
    id_cancion   BIGINT  NOT NULL,
    numero_pista INTEGER NOT NULL,
    CONSTRAINT pk_album_cancion PRIMARY KEY (id_album, id_cancion),
    CONSTRAINT uq_album_pista   UNIQUE (id_album, numero_pista),
    CONSTRAINT fk_alc_album FOREIGN KEY (id_album)
        REFERENCES album (id_album) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_alc_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_alc_pista CHECK (numero_pista > 0)
);

CREATE TABLE cancion_genero (
    id_cancion BIGINT  NOT NULL,
    id_genero  INTEGER NOT NULL,
    CONSTRAINT pk_cancion_genero PRIMARY KEY (id_cancion, id_genero),
    CONSTRAINT fk_cg_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_cg_genero FOREIGN KEY (id_genero)
        REFERENCES genero (id_genero) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE cancion_tema (
    id_cancion        BIGINT      NOT NULL,
    id_tema           INTEGER     NOT NULL,
    metodo_asignacion VARCHAR(30) NOT NULL,
    CONSTRAINT pk_cancion_tema PRIMARY KEY (id_cancion, id_tema),
    CONSTRAINT fk_ct_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ct_tema FOREIGN KEY (id_tema)
        REFERENCES tema (id_tema) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_ct_metodo CHECK (metodo_asignacion IN ('manual', 'metadatos', 'automatico'))
);

CREATE TABLE album_imagen (
    id_album             INTEGER NOT NULL,
    id_imagen            INTEGER NOT NULL,
    es_portada_principal BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_album_imagen PRIMARY KEY (id_album, id_imagen),
    CONSTRAINT fk_ai_album FOREIGN KEY (id_album)
        REFERENCES album (id_album) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ai_imagen FOREIGN KEY (id_imagen)
        REFERENCES imagen (id_imagen) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Como máximo una portada principal por álbum
CREATE UNIQUE INDEX uq_album_portada_principal
    ON album_imagen (id_album) WHERE es_portada_principal;

-- =====================================================================
-- 2. DOMINIO: LETRAS Y CHUNKING
-- =====================================================================

CREATE TABLE letra (
    id_letra   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cancion BIGINT       NOT NULL,
    id_idioma  INTEGER      NOT NULL,
    texto      TEXT         NOT NULL,
    fuente     VARCHAR(255),
    version    VARCHAR(40)  NOT NULL,
    CONSTRAINT pk_letra PRIMARY KEY (id_letra),
    CONSTRAINT uq_letra_cancion_idioma_version UNIQUE (id_cancion, id_idioma, version),
    CONSTRAINT fk_letra_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_letra_idioma FOREIGN KEY (id_idioma)
        REFERENCES idioma (id_idioma) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE fragmento_letra (
    id_fragmento        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_letra            INTEGER     NOT NULL,
    numero_fragmento    INTEGER     NOT NULL,
    texto_fragmento     TEXT        NOT NULL,
    estrategia_chunking VARCHAR(30) NOT NULL,
    token_inicio        INTEGER,
    token_fin           INTEGER,
    CONSTRAINT pk_fragmento_letra PRIMARY KEY (id_fragmento),
    CONSTRAINT uq_fragmento_letra_estrategia_num
        UNIQUE (id_letra, estrategia_chunking, numero_fragmento),
    CONSTRAINT fk_fl_letra FOREIGN KEY (id_letra)
        REFERENCES letra (id_letra) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_fl_numero CHECK (numero_fragmento > 0),
    CONSTRAINT ck_fl_tokens CHECK (
        token_inicio IS NULL OR token_fin IS NULL OR token_fin >= token_inicio
    )
);

-- =====================================================================
-- 3. DOMINIO: EMBEDDINGS (pgvector)
--    La dimensión de cada columna debe coincidir con el modelo usado.
--    Al fijar la dimensión por tabla se evita mezclar vectores incompatibles.
-- =====================================================================

CREATE TABLE embedding_texto (
    id_embedding_texto BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_fragmento       BIGINT       NOT NULL,
    modelo             VARCHAR(100) NOT NULL,
    version_modelo     VARCHAR(50),
    vector_embedding   VECTOR(384)  NOT NULL,
    fecha_generacion   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_embedding_texto PRIMARY KEY (id_embedding_texto),
    CONSTRAINT fk_et_fragmento FOREIGN KEY (id_fragmento)
        REFERENCES fragmento_letra (id_fragmento) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_embedding_texto_frag_modelo
    ON embedding_texto (id_fragmento, modelo, COALESCE(version_modelo, ''));

CREATE TABLE embedding_imagen (
    id_embedding_imagen BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_imagen           INTEGER      NOT NULL,
    modelo              VARCHAR(100) NOT NULL,
    vector_embedding    VECTOR(512)  NOT NULL,
    fecha_generacion    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_embedding_imagen PRIMARY KEY (id_embedding_imagen),
    CONSTRAINT uq_embedding_imagen_modelo UNIQUE (id_imagen, modelo),
    CONSTRAINT fk_ei_imagen FOREIGN KEY (id_imagen)
        REFERENCES imagen (id_imagen) ON UPDATE CASCADE ON DELETE CASCADE
);

-- VECTOR(512) es un valor de ejemplo (p. ej. CLAP). Ajústalo al modelo de audio elegido.
CREATE TABLE embedding_audio (
    id_embedding_audio BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_audio           BIGINT       NOT NULL,
    modelo             VARCHAR(100) NOT NULL,
    version_modelo     VARCHAR(50),
    vector_embedding   VECTOR(512)  NOT NULL,
    fecha_generacion   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_embedding_audio PRIMARY KEY (id_embedding_audio),
    CONSTRAINT fk_ea_audio FOREIGN KEY (id_audio)
        REFERENCES archivo_audio (id_audio) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_embedding_audio_audio_modelo
    ON embedding_audio (id_audio, modelo, COALESCE(version_modelo, ''));

-- =====================================================================
-- 4. DOMINIO: USUARIO Y COMPORTAMIENTO
-- =====================================================================

CREATE TABLE usuario (
    id_usuario       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(120) NOT NULL,
    email            VARCHAR(254) NOT NULL,
    fecha_registro   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    zona_horaria     VARCHAR(50),
    idioma_preferido VARCHAR(10),
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

CREATE TABLE preferencia_usuario (
    id_preferencia    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario        BIGINT       NOT NULL,
    tipo_preferencia  VARCHAR(30)  NOT NULL,
    valor_preferencia VARCHAR(255) NOT NULL,
    peso              NUMERIC(4,3),   -- en el PDF figura con el nombre 'tipo_preferencia' (error de transcripción)
    CONSTRAINT pk_preferencia_usuario PRIMARY KEY (id_preferencia),
    CONSTRAINT fk_pu_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_pu_peso CHECK (peso IS NULL OR peso BETWEEN 0 AND 1)
);

CREATE TABLE lista_reproduccion (
    id_lista       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario     BIGINT       NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    descripcion    TEXT,
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    es_publica     BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_lista_reproduccion PRIMARY KEY (id_lista),
    CONSTRAINT fk_lr_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE lista_cancion (
    id_lista       BIGINT    NOT NULL,
    id_cancion     BIGINT    NOT NULL,
    posicion       INTEGER   NOT NULL,
    fecha_agregada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_lista_cancion PRIMARY KEY (id_lista, id_cancion),
    -- Diferible para poder reordenar posiciones dentro de una transacción
    CONSTRAINT uq_lista_posicion UNIQUE (id_lista, posicion) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_lc_lista FOREIGN KEY (id_lista)
        REFERENCES lista_reproduccion (id_lista) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_lc_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_lc_posicion CHECK (posicion > 0)
);

CREATE TABLE reproduccion (
    id_reproduccion             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario                  BIGINT    NOT NULL,
    id_cancion                  BIGINT    NOT NULL,
    fecha_hora_inicio           TIMESTAMP NOT NULL,
    duracion_escuchada_segundos INTEGER   NOT NULL,
    completada                  BOOLEAN   NOT NULL,
    origen_reproduccion         VARCHAR(30),
    CONSTRAINT pk_reproduccion PRIMARY KEY (id_reproduccion),
    CONSTRAINT fk_rep_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_rep_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_rep_duracion CHECK (duracion_escuchada_segundos >= 0)
);

CREATE TABLE interaccion_usuario (
    id_interaccion   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       BIGINT      NOT NULL,
    id_cancion       BIGINT      NOT NULL,
    tipo_interaccion VARCHAR(30) NOT NULL,
    fecha_hora       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_interaccion_usuario PRIMARY KEY (id_interaccion),
    CONSTRAINT fk_iu_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_iu_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE recomendacion (
    id_recomendacion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       BIGINT       NOT NULL,
    id_cancion       BIGINT       NOT NULL,
    fecha_hora       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    puntaje          NUMERIC(8,6),
    motivo           TEXT,
    estado           VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_recomendacion PRIMARY KEY (id_recomendacion),
    CONSTRAINT fk_rec_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_rec_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE
);

-- =====================================================================
-- 5. DOMINIO: NÚCLEO RAG (consultas, resultados, respuestas, evaluación)
-- =====================================================================

CREATE TABLE consulta (
    id_consulta     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario      BIGINT,               -- NULL = consulta anónima
    texto_pregunta  TEXT        NOT NULL,
    fecha_consulta  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_consulta   VARCHAR(20) NOT NULL,
    CONSTRAINT pk_consulta PRIMARY KEY (id_consulta),
    CONSTRAINT fk_consulta_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_consulta_tipo CHECK (tipo_consulta IN ('texto', 'imagen', 'hibrida'))
);

CREATE TABLE embedding_consulta (
    id_embedding_consulta BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_consulta           BIGINT       NOT NULL,
    modelo                VARCHAR(100) NOT NULL,
    vector_embedding      VECTOR(384)  NOT NULL,
    fecha_generacion      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_embedding_consulta PRIMARY KEY (id_embedding_consulta),
    CONSTRAINT uq_embedding_consulta_modelo UNIQUE (id_consulta, modelo),
    CONSTRAINT fk_ec_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Cada resultado recupera exactamente UNA entidad: fragmento, imagen o canción
CREATE TABLE resultado_busqueda (
    id_resultado      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_consulta       BIGINT      NOT NULL,
    id_fragmento      BIGINT,
    id_imagen         INTEGER,
    id_cancion        BIGINT,
    tipo_recuperacion VARCHAR(20) NOT NULL,
    score_similitud   DOUBLE PRECISION,
    posicion          INTEGER     NOT NULL,
    CONSTRAINT pk_resultado_busqueda PRIMARY KEY (id_resultado),
    CONSTRAINT uq_resultado_consulta_posicion UNIQUE (id_consulta, posicion),
    CONSTRAINT fk_rb_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_rb_fragmento FOREIGN KEY (id_fragmento)
        REFERENCES fragmento_letra (id_fragmento) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_rb_imagen FOREIGN KEY (id_imagen)
        REFERENCES imagen (id_imagen) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_rb_cancion FOREIGN KEY (id_cancion)
        REFERENCES cancion (id_cancion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_rb_posicion CHECK (posicion > 0),
    CONSTRAINT ck_rb_exactamente_uno
        CHECK (num_nonnulls(id_fragmento, id_imagen, id_cancion) = 1)
);

CREATE TABLE respuesta_rag (
    id_respuesta        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_consulta         BIGINT       NOT NULL,
    texto_respuesta     TEXT         NOT NULL,
    modelo_llm          VARCHAR(100) NOT NULL,
    fecha_generacion    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tiempo_respuesta_ms INTEGER,
    CONSTRAINT pk_respuesta_rag PRIMARY KEY (id_respuesta),
    CONSTRAINT fk_rr_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_rr_tiempo CHECK (tiempo_respuesta_ms IS NULL OR tiempo_respuesta_ms >= 0)
);

CREATE TABLE evaluacion_rag (
    id_evaluacion      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_respuesta       BIGINT        NOT NULL,
    faithfulness       NUMERIC(4,3),
    answer_relevancy   NUMERIC(4,3),
    context_recall     NUMERIC(4,3),
    context_precision  NUMERIC(4,3),
    modelo_evaluacion  VARCHAR(100)  NOT NULL,
    fecha_evaluacion   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_evaluacion_rag PRIMARY KEY (id_evaluacion),
    CONSTRAINT uq_evaluacion_respuesta UNIQUE (id_respuesta),   -- relación 1:1
    CONSTRAINT fk_er_respuesta FOREIGN KEY (id_respuesta)
        REFERENCES respuesta_rag (id_respuesta) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_er_faithfulness      CHECK (faithfulness      BETWEEN 0 AND 1),
    CONSTRAINT ck_er_answer_relevancy  CHECK (answer_relevancy  BETWEEN 0 AND 1),
    CONSTRAINT ck_er_context_recall    CHECK (context_recall    BETWEEN 0 AND 1),
    CONSTRAINT ck_er_context_precision CHECK (context_precision BETWEEN 0 AND 1)
);

-- =====================================================================
-- 6. ÍNDICES SOBRE LLAVES FORÁNEAS (consultas y joins frecuentes)
-- =====================================================================

CREATE INDEX idx_artista_pais            ON artista (id_pais);
CREATE INDEX idx_album_sello             ON album (id_sello);
CREATE INDEX idx_audio_cancion           ON archivo_audio (id_cancion);
CREATE INDEX idx_ca_artista              ON cancion_artista (id_artista);
CREATE INDEX idx_alc_cancion             ON album_cancion (id_cancion);
CREATE INDEX idx_cg_genero               ON cancion_genero (id_genero);
CREATE INDEX idx_ct_tema                 ON cancion_tema (id_tema);
CREATE INDEX idx_ai_imagen               ON album_imagen (id_imagen);
CREATE INDEX idx_letra_idioma            ON letra (id_idioma);
CREATE INDEX idx_fragmento_letra         ON fragmento_letra (id_letra);
CREATE INDEX idx_pref_usuario            ON preferencia_usuario (id_usuario);
CREATE INDEX idx_lista_usuario           ON lista_reproduccion (id_usuario);
CREATE INDEX idx_lc_cancion              ON lista_cancion (id_cancion);
CREATE INDEX idx_rep_usuario_fecha       ON reproduccion (id_usuario, fecha_hora_inicio DESC);
CREATE INDEX idx_rep_cancion             ON reproduccion (id_cancion);
CREATE INDEX idx_inter_usuario_fecha     ON interaccion_usuario (id_usuario, fecha_hora DESC);
CREATE INDEX idx_inter_cancion           ON interaccion_usuario (id_cancion);
CREATE INDEX idx_rec_usuario_fecha       ON recomendacion (id_usuario, fecha_hora DESC);
CREATE INDEX idx_rec_cancion             ON recomendacion (id_cancion);
CREATE INDEX idx_consulta_usuario_fecha  ON consulta (id_usuario, fecha_consulta DESC);
CREATE INDEX idx_rb_fragmento            ON resultado_busqueda (id_fragmento) WHERE id_fragmento IS NOT NULL;
CREATE INDEX idx_rb_imagen               ON resultado_busqueda (id_imagen)    WHERE id_imagen    IS NOT NULL;
CREATE INDEX idx_rb_cancion              ON resultado_busqueda (id_cancion)   WHERE id_cancion   IS NOT NULL;
CREATE INDEX idx_rr_consulta             ON respuesta_rag (id_consulta);

-- =====================================================================
-- 7. ÍNDICES VECTORIALES (pgvector, HNSW, similitud coseno)
--    Para usar distancia L2 o producto interno cambia el operador:
--    vector_l2_ops / vector_ip_ops
-- =====================================================================

CREATE INDEX idx_hnsw_embedding_texto
    ON embedding_texto   USING hnsw (vector_embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);

CREATE INDEX idx_hnsw_embedding_imagen
    ON embedding_imagen  USING hnsw (vector_embedding vector_cosine_ops)
